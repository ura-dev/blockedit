"""例: 他ドキュメントを参照させるだけの文を、段落から丸ごと落とす。

`SCOPE="match"` の見本であり、`blockedit_selftest.py` が既定で読むタスクでもある
(PATTERN / RESIDUE / validate がゲートのケース表と対になっている)。

**このタスク自体は判断ラダー1段目でも書ける。**正規表現で PATTERN の一致を消せば同じ
結果になる。ここでLLMを通しているのは、実運用ランナーの配線(選択→送信→ゲート→貼り戻し
→git diff)を実ファイルで1本通すためのスモークテストという位置付け。

リンク記法を表示テキストに畳む機械的な部分も1段目で、`example_link_flatten.py`
(`UNIT="line"` / transform)が担当する。こちらは「文ごと消す」側だけを持つ。

SCOPE="match" なので PATTERN が「選択」と「改変を許可する範囲」を兼ねる。文を丸ごと
消す操作を許すので**文全体**を範囲に取る(リンクだけを範囲にすると、削除が局所性ゲートに
落ちる)。
逆に範囲を広げすぎない — ゲートは「一致範囲を、その部分文字列で置き換える」ことしか
許さないので、範囲の広さがそのままモデルに与える裁量になる。
1行内で閉じる形で書く(ゲートの範囲検査は行単位)。
"""

import re

FILES = ["docs/**/*.md"]

# 役目を終えた記録は書き換えない。過去の実測ログを現在の規約で直すと履歴が壊れる
EXCLUDE = ["docs/_archive/**/*.md"]

UNIT = "para"      # 段落を見せる
SCOPE = "match"    # 改変を許すのは PATTERN の一致範囲だけ

_LINK = r"\[[^\]\n]+\]\([^)\n]+\)"
_REF = r"(?:参照|詳細)"

# リンクを含み、かつ参照を促す語を含む文。`。` を越えないので前後の文には手が出ない。
# リンクを含むだけの文(内容を述べている文)は選ばない — 消す対象ではないため。
PATTERN = re.compile(rf"[^。\n]*(?:{_REF}[^。\n]*{_LINK}|{_LINK}[^。\n]*{_REF})[^。\n]*。")

# 完了判定は PATTERN を流用せず、緩いパターンで別に取る。PATTERN は完全形しか拾わない
# ので、開き括弧だけ消えた `表示](パス)` を「残っていない」と誤判定する。
# 同じ段落に参照文でないリンクがある場合を誤検出しないよう、`](` 単独では見ない。
RESIDUE = re.compile(rf"{_REF}[^。\n]*\]\(|\]\([^。\n]*{_REF}")

INSTRUCTION = """以下のMarkdownの一節には、他のドキュメントを参照させるだけの文があります
(`[表示テキスト](パス)` 形式のリンクを含み、「〜を参照」「詳細は〜」の形をとる文)。
その文を丸ごと削除した一節を出力してください。

- 削除するのはその文だけです。前後の文・見出し・箇条書きの記号・空白・改行は
  1文字も変えず、原文のまま写してください
- 文を消して前後がつながらなくなっても、言い換えや補足を足さないでください
- 出力は書き直した一節の全文だけです。説明・見出し・コードブロックを付けないでください

よくある誤り:
  入力: 温度0は貪欲デコードなので再実行しても同じ出力になります。計測手順は [bench](../bench/README.md) を参照。
  誤り: 温度0は貪欲デコードなので再実行しても同じ出力になります。計測手順は bench を参照。
  正解: 温度0は貪欲デコードなので再実行しても同じ出力になります。"""


def validate(before, after):
    """このタスクは文字を減らす操作しかしない。増えたら何かを持ち込んでいる。"""
    if len(after) > len(before):
        return f"出力が入力より長い({len(before)} -> {len(after)}文字)"
    return None
